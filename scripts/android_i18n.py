def normalize_lang(raw: str) -> str:
    val = str(raw or "id").strip()
    lower_map = {k.lower(): k for k in SUPPORTED_LANGS}
    return lower_map.get(val.lower(), "id")


def next_lang(current: str) -> str:
    cur = normalize_lang(current)
    idx = SUPPORTED_LANGS.index(cur)
    return SUPPORTED_LANGS[(idx + 1) % len(SUPPORTED_LANGS)]


def tr(lang: str, key: str, **kwargs) -> str:
    norm = normalize_lang(lang)
    text = STRINGS.get(norm, STRINGS["id"]).get(key, STRINGS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text
